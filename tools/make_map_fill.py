"""Build the outline + area table used by the newsroom `mapfill` widget (a country that fills up to X%).

Usage (from the Video/ root):
  python3 tools/make_map_fill.py india

Reads library/maps/<id>/outline.geojson (India: official boundaries, see map.json) and writes
remotion/src/templates/newsroom/maps/<id>.ts with:
  - path: the outline as one SVG path (equirectangular, like map.json; lightly simplified),
  - viewBox, and
  - below: 101 numbers, below[k] = share of the country's AREA lying below height k% (from the bottom),
    so the widget can stop its fill exactly at, say, 38% of the area instead of 38% of the height.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from studio_paths import CODE_ROOT, CONTENT_ROOT  # noqa: E402

W = 1000.0  # path units across the bounding box
TOL = 1.5  # simplification tolerance in path units (~0.05°), invisible at phone size


def rings_of(geom: dict) -> list[list[tuple[float, float]]]:
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return [[(x, y) for x, y in ring] for poly in polys for ring in poly]


def simplify(pts: list[tuple[float, float]], tol: float) -> list[tuple[float, float]]:
    """Douglas–Peucker, iterative."""
    if len(pts) < 4:
        return pts
    keep = [False] * len(pts)
    # a closed ring starts and ends on the same point, so anchor its far point too (else every
    # distance is measured to a zero-length segment and nothing is ever dropped)
    mid = len(pts) // 2
    keep[0] = keep[mid] = keep[-1] = True
    stack = [(0, mid), (mid, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        n = (dx * dx + dy * dy) ** 0.5 or 1e-9
        best, idx = 0.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / n
            if d > best:
                best, idx = d, i
        if best > tol and idx > 0:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    out = [p for p, k in zip(pts, keep) if k]
    return out if len(out) >= 4 else pts


def main() -> None:
    map_id = sys.argv[1] if len(sys.argv) > 1 else "india"
    gj = json.loads((CONTENT_ROOT / "library/maps" / map_id / "outline.geojson").read_text())
    rings = [r for f in gj["features"] for r in rings_of(f["geometry"])]
    xs = [x for r in rings for x, _ in r]
    ys = [y for r in rings for _, y in r]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    s = W / (x1 - x0)
    H = (y1 - y0) * s
    proj = [[((x - x0) * s, (y1 - y) * s) for x, y in r] for r in rings]  # SVG y grows downwards
    simple = [simplify(r, TOL) for r in proj]

    path = " ".join("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in r) + " Z" for r in simple)

    # area below each height: scanline integration with the even-odd rule over the full-detail rings
    rows = 2000
    edges = [(a, b) for r in proj for a, b in zip(r, r[1:] + r[:1]) if a[1] != b[1]]
    width_at = []
    for i in range(rows):
        yy = (i + 0.5) / rows * H
        cross = sorted(ax + (yy - ay) * (bx - ax) / (by - ay) for (ax, ay), (bx, by) in edges if (ay <= yy < by) or (by <= yy < ay))
        width_at.append(sum(cross[k + 1] - cross[k] for k in range(0, len(cross) - 1, 2)))
    total = sum(width_at)
    below = []
    for k in range(101):  # k% of the height, measured from the bottom
        cut = rows - round(k / 100 * rows)
        below.append(round(sum(width_at[cut:]) / total, 4))

    out = CODE_ROOT / "remotion/src/templates/newsroom/maps" / f"{map_id}.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"// Generated by tools/make_map_fill.py {map_id} from library/maps/{map_id}/outline.geojson. Do not edit.\n"
        f"// Equirectangular, {len(rings)} rings, simplified to {sum(len(r) for r in simple)} points.\n"
        f"export const viewBox = \"0 0 {W:.0f} {H:.0f}\";\n"
        f"export const width = {W:.0f};\nexport const height = {H:.0f};\n"
        f"// below[k] = share of the area below k% of the height (from the bottom)\n"
        f"export const below = {json.dumps(below)};\n"
        f"export const path = {json.dumps(path)};\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(CODE_ROOT)}: {sum(len(r) for r in simple)} points, {len(path) // 1024} KB path")


if __name__ == "__main__":
    main()
